use pistack_types::{ApiError, ApiResult};

pub(crate) fn validate_name(name: &str) -> ApiResult<()> {
    if name.trim().is_empty() || name.len() > 128 || name.contains('/') {
        return Err(ApiError::bad_request(
            "name must be 1-128 characters without '/'",
        ));
    }
    Ok(())
}
